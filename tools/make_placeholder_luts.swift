#!/usr/bin/env swift
// Generates procedural placeholder .cube LUTs for the MVP look set (spec §6.2).
//
// Usage (from ios/):  swift Tools/make_placeholder_luts.swift [output-dir]
// Default output dir: Hopea/Resources/Looks
//
// LUTs operate on gamma-encoded Display P3 values in [0, 1] (LookPipeline applies them
// with CIColorCubeWithColorSpace in Display P3). These are deliberately simple
// approximations of each look's description; final LUTs will be designed externally and
// dropped in with the same file names.

import Foundation

typealias RGB = (r: Double, g: Double, b: Double)

let size = 33

func clamp(_ x: Double) -> Double { min(max(x, 0), 1) }
func mix(_ a: Double, _ b: Double, _ t: Double) -> Double { a + (b - a) * t }
func smoothstep(_ e0: Double, _ e1: Double, _ x: Double) -> Double {
    let t = clamp((x - e0) / (e1 - e0))
    return t * t * (3 - 2 * t)
}
func luma(_ c: RGB) -> Double { 0.2126 * c.r + 0.7152 * c.g + 0.0722 * c.b }

/// Blend toward a smoothstep S-curve (positive) or toward mid-grey (negative) for contrast.
func contrast(_ x: Double, _ amount: Double) -> Double {
    amount >= 0 ? mix(x, smoothstep(0, 1, x), amount) : mix(x, 0.5, -amount)
}

/// Gentle quadratic highlight shoulder above 0.7. Monotonic for rolloff <= 0.5.
func shoulder(_ x: Double, _ rolloff: Double) -> Double {
    let over = max(0, x - 0.7)
    return x - rolloff * over * over / 0.3
}

/// Lift blacks: maps 0 → lift while keeping 1 → 1.
func lift(_ x: Double, _ amount: Double) -> Double { amount + (1 - amount) * x }

func tone(_ c: RGB, contrast k: Double, rolloff: Double, lift l: Double) -> RGB {
    func f(_ x: Double) -> Double { lift(shoulder(contrast(x, k), rolloff), l) }
    return (f(c.r), f(c.g), f(c.b))
}

func saturate(_ c: RGB, _ s: Double) -> RGB {
    let y = luma(c)
    return (mix(y, c.r, s), mix(y, c.g, s), mix(y, c.b, s))
}

// MARK: - Looks

/// Hopea: soft Nordic light — cool-neutral, gentle highlight roll-off, true skin, lifted shadows.
func hopea(_ input: RGB) -> RGB {
    var c = tone(input, contrast: 0.08, rolloff: 0.15, lift: 0.025)
    let y = luma(c)
    // Cool-neutral: a whisper of blue in the mids/highlights, slightly less red.
    let mids = smoothstep(0.15, 0.8, y)
    c = (c.r - 0.008 * mids, c.g, c.b + 0.014 * mids)
    // Keep skin (r > g > b) close to its original saturation, ease everything else slightly.
    let skin = clamp((c.r - c.g) * 6) * clamp((c.g - c.b) * 6)
    return saturate(c, mix(0.93, 1.0, skin))
}

/// Americana: warm highlights, faded blues, slightly lifted blacks, road-trip feel.
func americana(_ input: RGB) -> RGB {
    var c = tone(input, contrast: 0.12, rolloff: 0.12, lift: 0.06)
    let y = luma(c)
    let highlights = smoothstep(0.4, 1.0, y)
    c = (c.r + 0.05 * highlights, c.g + 0.02 * highlights, c.b - 0.045 * highlights)
    // Fade blues: desaturate and nudge toward cyan where blue dominates.
    let blueness = clamp((c.b - max(c.r, c.g)) * 3)
    let faded = saturate(c, 0.55)
    c = (mix(c.r, faded.r, blueness), mix(c.g, faded.g + 0.02, blueness), mix(c.b, faded.b, blueness))
    return saturate(c, 0.92)
}

/// Harbor: muted, desaturated cool tones; teal shadows, soft contrast.
func harbor(_ input: RGB) -> RGB {
    var c = tone(input, contrast: -0.06, rolloff: 0.1, lift: 0.03)
    c = saturate(c, 0.65)
    let y = luma(c)
    let shadows = 1 - smoothstep(0.0, 0.55, y)
    c = (c.r - 0.03 * shadows, c.g + 0.012 * shadows, c.b + 0.03 * shadows)
    // Slight overall coolness.
    return (c.r - 0.006, c.g, c.b + 0.01)
}

/// Silver: monochrome; rich midtones, gentle contrast (grain comes from looks.json).
func silver(_ input: RGB) -> RGB {
    // A touch of "red filter" weighting for richer skies and skin.
    let y = 0.32 * input.r + 0.58 * input.g + 0.10 * input.b
    var v = contrast(y, 0.15)
    v = shoulder(v, 0.1)
    v = lift(v, 0.02)
    // Rich midtones: a small mid-lift that leaves black and white anchored.
    v = v + 0.03 * sin(Double.pi * v)
    return (v, v, v)
}

// MARK: - Writer

func writeCube(name: String, title: String, to dir: URL, transform: (RGB) -> RGB) throws {
    var out = "# Hopea placeholder LUT — generated by Tools/make_placeholder_luts.swift\n"
    out += "# Gamma-encoded Display P3 in, Display P3 out.\n"
    out += "TITLE \"\(title)\"\n"
    out += "LUT_3D_SIZE \(size)\n"
    out += "DOMAIN_MIN 0.0 0.0 0.0\nDOMAIN_MAX 1.0 1.0 1.0\n"
    let n = Double(size - 1)
    // .cube order: red varies fastest, then green, then blue.
    for b in 0..<size {
        for g in 0..<size {
            for r in 0..<size {
                let c = transform((Double(r) / n, Double(g) / n, Double(b) / n))
                out += String(format: "%.6f %.6f %.6f\n", clamp(c.r), clamp(c.g), clamp(c.b))
            }
        }
    }
    let url = dir.appendingPathComponent("\(name).cube")
    try out.write(to: url, atomically: true, encoding: .utf8)
    print("wrote \(url.path)")
}

let args = CommandLine.arguments
let outDir = URL(fileURLWithPath: args.count > 1 ? args[1] : "Hopea/Resources/Looks")
try FileManager.default.createDirectory(at: outDir, withIntermediateDirectories: true)
try writeCube(name: "hopea", title: "Hopea", to: outDir, transform: hopea)
try writeCube(name: "americana", title: "Americana", to: outDir, transform: americana)
try writeCube(name: "harbor", title: "Harbor", to: outDir, transform: harbor)
try writeCube(name: "silver", title: "Silver", to: outDir, transform: silver)
